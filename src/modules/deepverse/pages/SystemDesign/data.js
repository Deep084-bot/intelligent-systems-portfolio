export function createComponentInstance(comp) {
  return {
    ...comp,
    instanceId: `${comp.id}-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
  }
}

export function findItem(id) {
  for (const cat of CATEGORIES) {
    for (const item of cat.items) {
      if (item.id === id) return { category: cat, item }
    }
  }
  return null
}

